@router.post("/{analysis_id}/gradcam")
def create_gradcam(analysis_id: str, user: User = Depends(current_user), db: Session = Depends(get_db)):
    """Feature 39: generate a classifier Grad-CAM explanation on demand."""
    row = db.get(Analysis, analysis_id)
    if row is None or not can_access(row, user):
        raise HTTPException(status_code=404, detail="Analysis not found")
    original = Path(row.artifact_dir) / "original.jpg"
    if not original.exists():
        raise HTTPException(status_code=404, detail="Original image artifact is unavailable")
    try:
        engine.gradcam(original.read_bytes(), Path(row.artifact_dir), row.caption)
    except Exception as exc:
        raise HTTPException(status_code=500, detail=f"Could not create Grad-CAM: {exc}") from exc
    return {"artifact": settings.api_prefix + "/analyses/" + row.id + "/artifacts/gradcam.jpg", "method": "Grad-CAM of manipulation classification logit"}


@router.get("/{analysis_id}/localization-preview")
def localization_preview(analysis_id: str, threshold: float = Query(0.55, ge=0.0, le=1.0), user: User = Depends(current_user), db: Session = Depends(get_db)):
    """Feature 28: re-threshold a saved neural probability map without new inference."""
    row = db.get(Analysis, analysis_id)
    if row is None or not can_access(row, user):
        raise HTTPException(status_code=404, detail="Analysis not found")
    path = Path(row.artifact_dir) / "probability_map.npy"
    if not path.exists():
        raise HTTPException(status_code=404, detail="Raw probability map is unavailable for this older analysis")
    probability = np.load(path)
    binary = (probability >= threshold).astype(np.uint8)
    count, labels, stats, _ = cv2.connectedComponentsWithStats(binary, connectivity=8)
    regions = []
    for label in range(1, count):
        x, y, width, height, area = (int(value) for value in stats[label])
        if area >= max(20, int(binary.size * 0.0006)):
            regions.append({"x": x, "y": y, "width": width, "height": height, "area_pct": round(100 * area / binary.size, 3)})
    return {"threshold": threshold, "highlighted_area_pct": round(float(binary.mean() * 100), 3), "regions": regions}


@router.get("/{analysis_id}/ground-truth-comparison")
def ground_truth_comparison(analysis_id: str, source_id: str, threshold: float = Query(0.55, ge=0.0, le=1.0), user: User = Depends(current_user), db: Session = Depends(get_db)):
    """Features 29–30: compare a saved prediction with an AutoSplice ground-truth mask."""
    row = db.get(Analysis, analysis_id)
    if row is None or not can_access(row, user):
        raise HTTPException(status_code=404, detail="Analysis not found")
    prediction_path = Path(row.artifact_dir) / "probability_map.npy"
    mask_path = Path(settings.model_checkpoint).resolve().parent.parent / "validation_data" / "Mask" / (str(source_id) + "_mask.png")
    if not prediction_path.exists() or not mask_path.exists():
        raise HTTPException(status_code=404, detail="Prediction map or ground-truth mask is unavailable")
    prediction = (np.load(prediction_path) >= threshold).astype(np.uint8)
    truth = cv2.imread(str(mask_path), cv2.IMREAD_GRAYSCALE)
    truth = (cv2.resize(truth, (prediction.shape[1], prediction.shape[0]), interpolation=cv2.INTER_NEAREST) > 127).astype(np.uint8)
    intersection = int(np.logical_and(prediction, truth).sum())
    pred_sum, truth_sum = int(prediction.sum()), int(truth.sum())
    union = int(np.logical_or(prediction, truth).sum())
    return {"source_id": source_id, "threshold": threshold, "dice": round((2 * intersection) / max(pred_sum + truth_sum, 1), 6), "iou": round(intersection / max(union, 1), 6), "ground_truth_mask": settings.api_prefix + "/analyses/dataset/masks/" + str(source_id)}
